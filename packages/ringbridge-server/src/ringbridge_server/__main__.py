"""`python -m ringbridge_server serve | migrate | downgrade | revision`."""

from __future__ import annotations

import argparse
from collections.abc import Sequence

from ringbridge_server import migrate
from ringbridge_server.settings import get_settings


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="ringbridge-server", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    serve = sub.add_parser("serve", help="Run the API server")
    serve.add_argument("--host", help="Bind address (default: RINGBRIDGE_HOST or 127.0.0.1)")
    serve.add_argument("--port", type=int, help="Port (default: RINGBRIDGE_PORT or 8088)")
    serve.add_argument("--migrate", action="store_true", help="Apply migrations before starting")

    up = sub.add_parser("migrate", help="Apply database migrations")
    up.add_argument("revision", nargs="?", default="head")

    down = sub.add_parser("downgrade", help="Revert database migrations")
    down.add_argument("revision", help="Target revision, e.g. -1 or base")

    rev = sub.add_parser("revision", help="Create a migration (autogenerated from the models)")
    rev.add_argument("-m", "--message", required=True)
    rev.add_argument("--empty", action="store_true", help="Do not autogenerate")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    settings = get_settings()

    if args.command == "migrate":
        migrate.upgrade(settings.database_url, args.revision)
    elif args.command == "downgrade":
        migrate.downgrade(settings.database_url, args.revision)
    elif args.command == "revision":
        migrate.revision(args.message, settings.database_url, autogenerate=not args.empty)
    else:  # serve
        import uvicorn

        from ringbridge_server.app import create_app
        from ringbridge_server.logs import configure_logging

        configure_logging(settings.log_level, settings.log_json)
        if args.migrate:
            migrate.upgrade(settings.database_url)
        uvicorn.run(
            create_app(settings),
            host=args.host or settings.host,
            port=args.port or settings.port,
            log_config=None,
            proxy_headers=True,
        )
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
